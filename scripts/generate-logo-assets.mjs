/**
 * Scans assets/Logos and writes components/profile/logoAssets.generated.ts.
 * Metro needs static require() paths — this is the RN-friendly “folder scan”.
 */
import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const logosDir = path.join(root, "assets", "Logos");
const outFile = path.join(root, "components", "profile", "logoAssets.generated.ts");

const imageRe = /\.(png|jpe?g|gif|webp)$/i;

function toId(filename) {
  return filename
    .replace(/\.[^.]+$/i, "")
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-|-$/g, "");
}

function toLabel(filename) {
  return filename.replace(/\.[^.]+$/i, "");
}

function escapeString(value) {
  return value.replace(/\\/g, "\\\\").replace(/"/g, '\\"');
}

if (!fs.existsSync(logosDir)) {
  console.error(`Missing folder: ${logosDir}`);
  process.exit(1);
}

const files = fs
  .readdirSync(logosDir)
  .filter((name) => imageRe.test(name))
  .sort((a, b) => a.localeCompare(b, undefined, { sensitivity: "base" }));

const entries = files.map((filename) => {
  const id = toId(filename);
  const label = toLabel(filename);
  const requirePath = `../../assets/Logos/${filename}`;
  return `  { id: "${escapeString(id)}", label: "${escapeString(label)}", source: require("${escapeString(requirePath)}") },`;
});

const source = `// AUTO-GENERATED by scripts/generate-logo-assets.mjs — do not edit.
// Re-run: npm run sync:logos (after adding images to assets/Logos)

import type { ImageSourcePropType } from "react-native";

export type ProfileLogo = {
  id: string;
  label: string;
  source: ImageSourcePropType;
};

export const profileLogos: readonly ProfileLogo[] = [
${entries.join("\n")}
] as const;
`;

fs.writeFileSync(outFile, source, "utf8");
console.log(`Wrote ${files.length} logo(s) to components/profile/logoAssets.generated.ts`);
