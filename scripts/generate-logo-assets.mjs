/**
 * Scans the gallery asset folders (assets/Logos + assets/Merch) and writes
 * components/profile/logoAssets.generated.ts.
 * Metro needs static require() paths — this is the RN-friendly “folder scan”.
 */
import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const outFile = path.join(root, "components", "profile", "logoAssets.generated.ts");

/** Folders scanned into the gallery. `category` is emitted per entry. */
const sources = [
  { dir: path.join(root, "assets", "Logos"), requireBase: "../../assets/Logos", category: "logo" },
  { dir: path.join(root, "assets", "Merch"), requireBase: "../../assets/Merch", category: "merch" },
];

const imageRe = /\.(png|jpe?g|gif|webp)$/i;

function toId(category, filename) {
  const base = filename
    .replace(/\.[^.]+$/i, "")
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-|-$/g, "");
  return `${category}-${base}`;
}

function toLabel(filename) {
  return filename.replace(/\.[^.]+$/i, "");
}

function escapeString(value) {
  return value.replace(/\\/g, "\\\\").replace(/"/g, '\\"');
}

const entries = [];
let scannedFolders = 0;

for (const { dir, requireBase, category } of sources) {
  if (!fs.existsSync(dir)) {
    console.warn(`Skipping missing folder: ${dir}`);
    continue;
  }
  scannedFolders += 1;

  const files = fs
    .readdirSync(dir)
    .filter((name) => imageRe.test(name))
    .sort((a, b) => a.localeCompare(b, undefined, { sensitivity: "base" }));

  for (const filename of files) {
    const id = toId(category, filename);
    const label = toLabel(filename);
    const requirePath = `${requireBase}/${filename}`;
    entries.push(
      `  { id: "${escapeString(id)}", label: "${escapeString(label)}", category: "${category}", source: require("${escapeString(requirePath)}") },`,
    );
  }
}

if (scannedFolders === 0) {
  console.error("No gallery asset folders found.");
  process.exit(1);
}

const source = `// AUTO-GENERATED by scripts/generate-logo-assets.mjs — do not edit.
// Re-run: npm run sync:logos (after adding images to assets/Logos or assets/Merch)

import type { ImageSourcePropType } from "react-native";

export type ProfileLogo = {
  id: string;
  label: string;
  category: "logo" | "merch";
  source: ImageSourcePropType;
};

export const profileLogos: readonly ProfileLogo[] = [
${entries.join("\n")}
] as const;
`;

fs.writeFileSync(outFile, source, "utf8");
console.log(`Wrote ${entries.length} asset(s) to components/profile/logoAssets.generated.ts`);
